import { it } from "vitest";
import { readFileSync, writeFileSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";
import mermaid from "mermaid";
import { drawIR, fits, svgSize, type Palette } from "../src/index";
import { dropStrayMarks, escapeAngles, toIR } from "../src/mermaid/index";

/**
 * The README's pictures: corpus sources drawn by the package itself, in the
 * README's --diagram-* values and the IBM Plex faces, into docs/gallery.html,
 * then one PNG per figure at 2x (docs/img/<name>.png), cropped to the drawing
 * with a margin of its surface. PNG, since GitHub shows an <img> SVG without
 * its web fonts. Outside a sandbox (a browser starts, fonts are fetched):
 *
 *   npx playwright install chromium   # once, the version package.json pins
 *   npx vitest run --config scripts/vitest.config.ts
 */

// Through a name: vite rewrites a literal `new URL(…, import.meta.url)` as
// an asset import, which here gave http://localhost:3000/.
const here = import.meta.url;
const root = fileURLToPath(new URL("..", here));
const at = (path: string) => root + path;

/** The figures, by eye: the kinds that read best as a picture. */
const figures = [
  { name: "mindmap", file: "mindmap-focus-en.mmd" },
  { name: "swimlane", file: "swimlane-loop.mmd" },
  { name: "sequence", file: "sequence-loop-opt.mmd" },
];

/** The README's theming example, resolved: a PNG has no stylesheet. */
const palette: Palette = {
  surface: "#151514",
  fg: "#ece8df",
  muted: "#a29e94",
  line: "#3b3935",
  tint: "#201f1c",
  accent: "#d97757",
  warn: "#e3a33f",
  sans: '"IBM Plex Sans", sans-serif',
  mono: '"IBM Plex Mono", monospace',
};

/** Every face and weight the drawing sets text in (draw.ts: 600 for bold,
 * 400 otherwise, either face). One missing is a synthesized bold or a
 * fallback face in the picture, so the capture fails instead. */
const faces = ["IBM Plex Sans", "IBM Plex Mono"];
const weights = [400, 600];

/** Space around a drawing, in CSS px, on its surface. */
const margin = 24;

type Figure = { name: string; svg: string; w: number; h: number };

it("draws the README's screenshots", async () => {
  mermaid.initialize({ startOnLoad: false, securityLevel: "strict" });
  const drawn: Figure[] = [];
  for (const f of figures) {
    const src = dropStrayMarks(
      readFileSync(at(`testdata/diagrams/${f.file}`), "utf8"),
    );
    const d = await mermaid.mermaidAPI.getDiagramFromText(escapeAngles(src));
    const ir = toIR(d.type, d.db);
    if (ir === null) throw new Error(`${f.file}: not a kind the package draws`);
    // A picture the package would hand to mermaid is not its own.
    if (!fits(ir)) throw new Error(`${f.file}: past the package's limits`);
    const { svg } = await drawIR(ir, f.name, { palette });
    const size = svgSize(svg);
    if (size === null) throw new Error(`${f.file}: the drawing has no size`);
    drawn.push({ name: f.name, svg, w: size.w, h: size.h });
  }

  const page = at("docs/gallery.html");
  writeFileSync(page, gallery(drawn));

  const browser = await chromium.launch();
  try {
    for (const d of drawn) {
      const tab = await browser.newPage({
        viewport: {
          width: Math.ceil(d.w) + 2 * margin,
          height: Math.ceil(d.h) + 2 * margin,
        },
        deviceScaleFactor: 2,
      });
      await tab.goto(`file://${page}#${d.name}`);
      const missing = await tab.evaluate(
        async ({ faces, weights }) => {
          await document.fonts.ready;
          const out: string[] = [];
          for (const face of faces)
            for (const w of weights) {
              const spec = `${w} 13px "${face}"`;
              // load() is empty for a face no stylesheet declares, where
              // check() alone would say true.
              const loaded = await document.fonts.load(spec);
              if (loaded.length === 0 || !document.fonts.check(spec))
                out.push(spec);
            }
          return out;
        },
        { faces, weights },
      );
      if (missing.length > 0)
        throw new Error(`fonts not loaded: ${missing.join(", ")}`);
      const out = at(`docs/img/${d.name}.png`);
      await tab.screenshot({ path: out });
      await tab.close();
      console.log(`${out}: ${Math.round(statSync(out).size / 1024)} kB`);
    }
  } finally {
    await browser.close();
  }
});

/** gallery is one page holding every figure; the URL's hash shows one. */
function gallery(drawn: Figure[]): string {
  const family = (face: string) =>
    `family=${face.replace(/ /g, "+")}:wght@${weights.join(";")}`;
  return `<!doctype html>
<!-- Generated by scripts/screenshots.ts; edit that, not this. -->
<html lang="en">
<head>
<meta charset="utf-8">
<title>diagram gallery</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?${faces.map(family).join("&")}&display=block">
<style>
  html, body { margin: 0; background: ${palette.surface}; }
  body { padding: ${margin}px; }
  figure { margin: 0; display: none; }
  figure.shown { display: block; }
  svg { display: block; }
</style>
</head>
<body>
${drawn.map((d) => `<figure id="${d.name}">${d.svg}</figure>`).join("\n")}
<script>
  const show = () => {
    for (const f of document.querySelectorAll("figure"))
      f.classList.toggle("shown", "#" + f.id === location.hash || location.hash === "");
  };
  show();
  addEventListener("hashchange", show);
</script>
</body>
</html>
`;
}
